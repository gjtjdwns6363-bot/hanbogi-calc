function policyRate(p, income, dep, metro) {
  if (p.rate != null) return p.rate;
  const row = p.table.find((r) => income <= r[0]); if (!row) return null;
  let c = p.cols.findIndex((x) => dep <= x); if (c < 0) c = p.cols.length - 1;
  return Math.max(1.0, +(row[1][c] - (metro ? 0 : 0.2)).toFixed(2));
}
